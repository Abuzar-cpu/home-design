"""Writes the room-size table in docs/ROOMS.md from the room list the tour itself uses
(rooms[] in src/js/52-rooms-labels.js), so the doc can't drift from the model.
   python3 tools/rooms.py           update docs/ROOMS.md
   python3 tools/rooms.py --check   exit 1 if docs/ROOMS.md is out of date (tools/check.py runs this)"""
import pathlib, re, sys
R = pathlib.Path(__file__).resolve().parents[1]
SRC, DOC = R / 'src' / 'js' / '52-rooms-labels.js', R / 'docs' / 'ROOMS.md'
A, B = '<!-- rooms:start (generated by tools/rooms.py, do not edit by hand) -->', '<!-- rooms:end -->'
# one room entry, on one line or spread over several (whatever the formatter chose)
ROW = re.compile(r"\{\s*n: (['\"])(.*?)\1,\s*d: '(.*?)',(\s*lv: 2,)?\s*x0: ([\d.]+),\s*x1: ([\d.]+),\s*z0: ([\d.]+),\s*z1: ([\d.]+)")

def table():
    rows = [m.groups() for m in ROW.finditer(SRC.read_text())]
    assert rows, 'no rooms found in ' + str(SRC)
    out = []
    for floor, up in (('Ground floor', False), ('Upper floor', True)):
        out += [f'**{floor}**', '', '| Room | Size | Area | x (m) | z (m) |', '|---|---|---|---|---|']
        for _, n, d, lv, x0, x1, z0, z1 in rows:
            if bool(lv) != up: continue
            size, _, area = d.partition(' · ')
            if area and not area.endswith('m²'): size, area = f'{size}, {area}', ''
            out.append(f'| {n} | {size} | {area or "–"} | {x0}–{x1} | {z0}–{z1} |')
        out.append('')
    return '\n'.join(out).rstrip() + '\n'

def render():
    s = DOC.read_text(); i, j = s.index(A) + len(A), s.index(B)
    return s[:i] + '\n' + table() + s[j:]

if __name__ == '__main__':
    new = render()
    if '--check' in sys.argv:
        ok = new == DOC.read_text(); print('rooms table', 'up to date' if ok else 'STALE: run python3 tools/rooms.py'); sys.exit(0 if ok else 1)
    DOC.write_text(new); print('updated', DOC.relative_to(R))
